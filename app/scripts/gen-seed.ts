/**
 * Generates supabase/migrations/0002_seed.sql from the TypeScript data files.
 *
 * The TS files stay the source of truth so the engine can run fully offline with no
 * database at all. This script projects them into SQL rather than duplicating them by
 * hand, because a dictionary that disagrees with itself across two files is worse than
 * having only one.
 *
 * Run: npm run gen:seed
 */
import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { INGREDIENTS } from '../src/data/ingredients';
import { RECIPES } from '../src/data/recipes';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', '..', 'supabase', 'migrations');

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (xs: readonly string[]) => `ARRAY[${xs.map(q).join(',')}]::text[]`;
const jsonOrNull = (v: unknown) => (v == null ? 'null' : `${q(JSON.stringify(v))}::jsonb`);

const lines: string[] = [
  '-- GENERATED by app/scripts/gen-seed.ts. Do not edit by hand.',
  '-- Regenerate with: cd app && npm run gen:seed',
  '',
  'begin;',
  '',
];

lines.push('-- ingredients ------------------------------------------------------------');
for (const i of INGREDIENTS) {
  lines.push(
    `insert into ingredient (id,name,cls,unit,shelf_life_days,burn_per_adult_per_day,par_per_adult,aisle,allergens,jain_safe,vegan) values (` +
      [
        q(i.id),
        q(i.name),
        q(i.cls),
        q(i.unit),
        jsonOrNull(i.shelfLifeDays),
        String(i.burnPerAdultPerDay),
        String(i.parPerAdult),
        q(i.aisle),
        arr(i.allergens),
        String(i.jainSafe),
        String(i.vegan),
      ].join(',') +
      `) on conflict (id) do update set name=excluded.name, cls=excluded.cls, unit=excluded.unit,` +
      ` shelf_life_days=excluded.shelf_life_days, burn_per_adult_per_day=excluded.burn_per_adult_per_day,` +
      ` par_per_adult=excluded.par_per_adult, aisle=excluded.aisle, allergens=excluded.allergens,` +
      ` jain_safe=excluded.jain_safe, vegan=excluded.vegan;`,
  );
}

lines.push('', '-- aliases ---------------------------------------------------------------');
for (const i of INGREDIENTS) {
  // The canonical name is itself an alias, so lookup has one code path.
  const all = new Set([i.name.toLowerCase(), ...i.aliases.map((a) => a.toLowerCase())]);
  for (const a of all) {
    lines.push(
      `insert into ingredient_alias (alias,ingredient_id) values (${q(a)},${q(i.id)})` +
        ` on conflict (alias) do update set ingredient_id=excluded.ingredient_id;`,
    );
  }
}

lines.push('', '-- recipes ---------------------------------------------------------------');
for (const r of RECIPES) {
  lines.push(
    `insert into recipe (id,name,cuisine,moods,minutes,effort,diet,jain_safe,vegan,equipment,cooktop,verified,household_id) values (` +
      [
        q(r.id),
        q(r.name),
        q(r.cuisine),
        arr(r.moods),
        String(r.minutes),
        String(r.effort),
        q(r.diet),
        String(r.jainSafe),
        String(r.vegan),
        arr(r.equipment),
        q(r.cooktop),
        String(r.verified),
        'null',
      ].join(',') +
      `) on conflict (id) do update set name=excluded.name, cuisine=excluded.cuisine, moods=excluded.moods,` +
      ` minutes=excluded.minutes, effort=excluded.effort, diet=excluded.diet, jain_safe=excluded.jain_safe,` +
      ` vegan=excluded.vegan, equipment=excluded.equipment, cooktop=excluded.cooktop, verified=excluded.verified;`,
  );
  for (const ri of r.ingredients) {
    lines.push(
      `insert into recipe_ingredient (recipe_id,ingredient_id,qty_per_2_adults,unit,core) values (` +
        [q(r.id), q(ri.ingredientId), String(ri.qtyPer2Adults), q(ri.unit), String(ri.core)].join(
          ',',
        ) +
        `) on conflict (recipe_id,ingredient_id) do update set qty_per_2_adults=excluded.qty_per_2_adults,` +
        ` unit=excluded.unit, core=excluded.core;`,
    );
  }
}

lines.push('', 'commit;', '');

async function main() {
  await mkdir(OUT, { recursive: true });
  await writeFile(join(OUT, '0002_seed.sql'), lines.join('\n'));
  console.log(
    `wrote 0002_seed.sql: ${INGREDIENTS.length} ingredients, ${RECIPES.length} recipes, ${lines.length} lines`,
  );
}

void main();
